import os
import sqlite3
import psycopg
from psycopg import sql

SQLITE_FILE = "shopnear.db"

TABLES = [
    "users",
    "categories",
    "shops",
    "products",
    "reservations",
    "bargaining_requests",
    "platform_settings"
]

SCHEMA = [
    """
    CREATE TABLE users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT UNIQUE NOT NULL,
        password_hash TEXT NOT NULL,
        role TEXT NOT NULL CHECK (role IN ('customer', 'shopkeeper', 'admin')),
        created_at TEXT NOT NULL,
        username TEXT UNIQUE
    )
    """,
    """
    CREATE TABLE categories (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL UNIQUE
    )
    """,
    """
    CREATE TABLE shops (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner_id BIGINT NOT NULL REFERENCES users(id),
        shop_name TEXT NOT NULL,
        address TEXT NOT NULL,
        location TEXT NOT NULL,
        description TEXT,
        created_at TEXT NOT NULL,
        latitude DOUBLE PRECISION,
        longitude DOUBLE PRECISION
    )
    """,
    """
    CREATE TABLE products (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        category TEXT NOT NULL,
        price DOUBLE PRECISION NOT NULL,
        shop TEXT NOT NULL,
        location TEXT NOT NULL,
        stock BIGINT NOT NULL,
        image TEXT,
        owner_id BIGINT REFERENCES users(id),
        description TEXT
    )
    """,
    """
    CREATE TABLE reservations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id BIGINT REFERENCES products(id),
        product TEXT NOT NULL,
        price DOUBLE PRECISION NOT NULL,
        shop TEXT NOT NULL,
        location TEXT NOT NULL,
        status TEXT NOT NULL,
        date TEXT NOT NULL,
        user_id BIGINT REFERENCES users(id)
    )
    """,
    """
    CREATE TABLE bargaining_requests (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id BIGINT NOT NULL REFERENCES products(id),
        customer_id BIGINT NOT NULL REFERENCES users(id),
        shopkeeper_id BIGINT NOT NULL REFERENCES users(id),
        offered_price DOUBLE PRECISION NOT NULL,
        message TEXT,
        status TEXT NOT NULL DEFAULT 'Pending',
        created_at TEXT NOT NULL,
        updated_at TEXT,
        counter_price DOUBLE PRECISION
    )
    """,
    """
    CREATE TABLE platform_settings (
        id BIGINT PRIMARY KEY CHECK (id = 1),
        platform_name TEXT NOT NULL,
        contact_email TEXT,
        support_phone TEXT
    )
    """
]


def migrate():
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is not loaded.")

    if not os.path.exists(SQLITE_FILE):
        raise FileNotFoundError(SQLITE_FILE + " was not found.")

    sqlite_conn = sqlite3.connect(SQLITE_FILE)
    sqlite_conn.row_factory = sqlite3.Row

    try:
        source_counts = {}

        for table in TABLES:
            source_counts[table] = sqlite_conn.execute(
                f'SELECT COUNT(*) FROM "{table}"'
            ).fetchone()[0]

        print("LOCAL DATABASE RECORD COUNTS:")
        for table, count in source_counts.items():
            print(f"  {table}: {count}")

        with psycopg.connect(database_url, sslmode="require") as pg_conn:
            with pg_conn.cursor() as cur:

                cur.execute("""
                    SELECT table_name
                    FROM information_schema.tables
                    WHERE table_schema = 'public'
                      AND table_type = 'BASE TABLE'
                """)

                existing = [row[0] for row in cur.fetchall()]

                if existing:
                    raise RuntimeError(
                        "Neon is no longer empty. Migration stopped "
                        "to protect existing tables: " + str(existing)
                    )

                print("\nCreating PostgreSQL tables...")

                for statement in SCHEMA:
                    cur.execute(statement)

                print("Copying records...")

                for table in TABLES:
                    rows = sqlite_conn.execute(
                        f'SELECT * FROM "{table}"'
                    ).fetchall()

                    if not rows:
                        continue

                    columns = rows[0].keys()

                    insert_query = sql.SQL(
                        "INSERT INTO {} ({}) VALUES ({})"
                    ).format(
                        sql.Identifier(table),
                        sql.SQL(", ").join(
                            sql.Identifier(column) for column in columns
                        ),
                        sql.SQL(", ").join(
                            sql.Placeholder() for _ in columns
                        )
                    )

                    values = []

                    for row in rows:
                        record = dict(row)

                        if table == "reservations":
                            if record["product_id"] is not None:
                                product_exists = sqlite_conn.execute(
                                    "SELECT 1 FROM products WHERE id = ?",
                                    (record["product_id"],)
                                ).fetchone()

                                if product_exists is None:
                                    print(
                                        f"Preserving historical reservation "
                                        f"{record['id']} without deleted product reference."
                                    )
                                    record["product_id"] = None

                        values.append(
                            tuple(record[column] for column in columns)
                        )

                    cur.executemany(insert_query, values)

                print("\nSynchronizing ID sequences...")

                for table in TABLES:
                    if table == "platform_settings":
                        continue

                    cur.execute(
                        sql.SQL("""
                            SELECT setval(
                                pg_get_serial_sequence(
                                    'public.' || %s, 'id'
                                ),
                                COALESCE(MAX(id), 1),
                                MAX(id) IS NOT NULL
                            )
                            FROM {}
                        """).format(sql.Identifier(table)),
                        (table,)
                    )

                print("\nVERIFYING MIGRATED RECORD COUNTS:")

                for table in TABLES:
                    cur.execute(
                        sql.SQL("SELECT COUNT(*) FROM {}").format(
                            sql.Identifier(table)
                        )
                    )

                    migrated_count = cur.fetchone()[0]
                    original_count = source_counts[table]

                    print(
                        f"  {table}: "
                        f"{migrated_count}/{original_count}"
                    )

                    if migrated_count != original_count:
                        raise RuntimeError(
                            f"Record count mismatch in {table}."
                        )

        print("\nSUCCESS: All records migrated and verified!")

    finally:
        sqlite_conn.close()


if __name__ == "__main__":
    migrate()
